package com.example.test1.common.response;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * ====================================================================================
 * 【枚举】ResultCode —— 统一错误码字典
 * ====================================================================================
 *
 * ▌1. 为什么所有错误码都放一个枚举里？
 *   - 集中管理：所有业务错误一眼可见，避免散落各处重复定义；
 *   - 编译期检查：用枚举引用而不是写数字 100400，IDE 能自动补全、重命名；
 *   - 一致性：所有错误都用同一个枚举，方便前端做错误码映射表。
 *
 * ▌2. 编码规则（6 位整数，前 2 位业务域，后 4 位序号）：
 *   - 10xxxx 通用域（参数错误、权限、服务器错）
 *   - 20xxxx 问候服务域（业务专属错误）
 *   - 99xxxx 兜底域（未知异常）
 *   好处：看到一个码就知道是哪个业务报的，方便排查。
 *
 * ▌3. 字段：
 *   - code：数字业务码（前端按它分支处理）
 *   - message：默认提示语（可作为兜底文案，业务可覆写）
 * ====================================================================================
 */
@Getter
@AllArgsConstructor
public enum ResultCode {

    /* ---------------- 通用域 ---------------- */
    SUCCESS(100000, "操作成功"),
    BAD_REQUEST(100400, "请求参数错误"),
    UNAUTHORIZED(100401, "未授权"),
    FORBIDDEN(100403, "禁止访问"),
    NOT_FOUND(100404, "资源不存在"),
    METHOD_NOT_ALLOWED(100405, "请求方法不被允许"),
    INTERNAL_ERROR(100500, "系统内部错误"),

    /* ---------------- 问候服务域 ---------------- */
    GREETING_SCENE_NOT_SUPPORTED(200001, "不支持的问候场景"),
    GREETING_NAME_BLANK(200002, "称呼不能为空"),

    /* ---------------- 兜底域 ---------------- */
    UNKNOWN(990000, "未知异常");

    /** 业务码 */
    private final Integer code;

    /** 提示信息 */
    private final String message;

}
