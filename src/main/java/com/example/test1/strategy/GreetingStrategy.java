package com.example.test1.strategy;

import com.example.test1.enums.GreetingSceneEnum;

/**
 * ====================================================================================
 * 【策略模式】GreetingStrategy —— 问候策略的"统一契约"
 * ====================================================================================
 *
 * ▌1. 什么是策略模式？
 *   把"同一件事的不同做法"各自封装成类，调用方持有一个接口引用，
 *   运行时按需切换具体实现。
 *   类比：导航 App 同一条路可以选"驾车/步行/骑行"三种策略，
 *        调用方只调 navigate()，具体走哪条路由选的策略决定。
 *
 * ▌2. 这里怎么用？
 *   - 不同时段（早/午/晚）的问候语"措辞"不同；
 *   - 把每种措辞写成单独的策略类（MorningGreetingStrategy 等）；
 *   - Service 通过工厂按场景拿到对应策略，调 buildGreeting() 即可；
 *   - 新增一个场景（如"深夜"）只要新建一个策略实现类，不碰老代码。
 *
 * ▌3. 接口里只定义两个方法：
 *   - supportScene()：告诉工厂"我处理哪个场景"，用于自动注册到工厂；
 *   - buildGreeting()：真正的业务——根据称呼生成问候语。
 * ====================================================================================
 */
public interface GreetingStrategy {

    /**
     * 返回该策略所归属的场景。
     * <p>
     * 工厂启动时调这个方法，把策略按场景归类到 Map 中。
     *
     * @return 场景枚举
     */
    GreetingSceneEnum supportScene();

    /**
     * 根据称呼生成问候语。
     *
     * @param name 称呼
     * @return 问候语
     */
    String buildGreeting(String name);

}
